def chapter_of(lines):
    """行號 → 章節。"""
    out, cur = {}, "開頭四個發現"
    for i, line in enumerate(lines, 1):
        m = re.match(r"^## (\d+)　", line)
        if m:
            cur = f"第 {m.group(1)} 章"
        m2 = re.match(r"^### (\d+\.\d+)　", line)
        if m2:
            cur = f"第 {m2.group(1)} 節"
        if line.startswith("## 附錄"):
            cur = "附錄"
        if line.startswith("## 怎麼驗收"):
            cur = "怎麼驗收這份報告"
        out[i] = cur
    return out


def item_keywords(item):
    """項目名稱 → 可用來在句子裡比對的關鍵詞（去掉括號說明）。"""
    return [w for w in re.split(r"[／/、，,：:]", re.sub(r"[（(].*?[)）]", "", item))
            if len(w) >= 2]


