def _num(s):
    return float(re.match(r"\d+(?:\.\d+)?", s).group(0))


def evaluate(tok, ref, figs=None):
    """回傳 (是否通過, 事實卡說明)。"""
    desc = ref["desc"]
    if ref.get("design") or ref.get("skip"):
        return True, desc
    t = tok.replace(" ", "")
    # 排名
    m = re.fullmatch(r"第([一二三四五六七八九十])", t)
    if m:
        return (CN.index(m.group(1)) + 1 == ref["rank"]), desc
    # 中文量詞
    if t in QUAL_RANGE:
        v = ref.get("value")
        if v is None:
            v = ref["n"] / ref["d"]
        lo, hi = QUAL_RANGE[t]
        ok = (lo <= v < hi) if t not in ("過半", "過半數", "超過半數") else v > 0.5
        return ok, desc + f"｜「{t}」對應的範圍 {lo:.0%}–{hi:.0%}"
    # 百分點差（「21 與 20 個百分點」）
    m = re.fullmatch(r"(\d+)與(\d+)個百分點", t)
    if m:
        a, b = ref["value"]
        return (round(abs(a)) == int(m.group(1)) and round(abs(b)) == int(m.group(2))), desc
    # 百分比帶分子分母
    m = re.fullmatch(r"(\d+(?:\.\d+)?)%[（(](\d+)/(\d+)[）)]", t)
    if m:
        p, n, d = float(m.group(1)), int(m.group(2)), int(m.group(3))
        ok = (n, d) == (ref["n"], ref["d"]) and abs(100 * n / d - p) <= 0.5 + 1e-9
        return ok, desc
    # 百分比
    m = re.fullmatch(r"(\d+(?:\.\d+)?)%", t)
    if m:
        p = float(m.group(1))
        dec = len(m.group(1).split(".")[1]) if "." in m.group(1) else 0
        if ref.get("n") is not None and ref.get("d"):
            v = ref["n"] / ref["d"]
        else:
            v = ref["value"]
        tol = 0.5 * 10 ** (-dec) + 1e-6
        return abs(abs(v) * 100 - p) <= tol, desc
    # 人數或其他量詞（含表格裡的裸數字）
    m = re.match(r"(\d+)", t)
    if m:
        want = int(m.group(1))
        if ref.get("field") == "d":
            got = ref["d"]
        elif ref.get("field") == "calc":
            got = ref["value"]
        else:
            got = ref["n"]
        if "多個" in t:                       # 「10 多個」＝超過 10
            return got > want, desc
        return got == want, desc
    raise SystemExit(f"不認得的數字寫法：{tok}")


