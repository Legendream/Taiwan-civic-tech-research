# 每個來源都回傳 dict：value（比例 0–1 或人數）、n、d、desc（給事實卡的說明）


def I(item, n=None, d=None, field="pct"):
    rows = _IDX[_IDX["項目"] == item]
    if n is not None:
        rows = rows[rows["分子"] == n]
    if d is not None:
        rows = rows[rows["分母"] == d]
    pairs = {(int(r["分子"]), int(r["分母"])) for _, r in rows.iterrows()}
    if len(pairs) != 1:
        raise SystemExit(f"99_數字索引 找不到唯一一列：項目={item} n={n} d={d}（找到 {len(rows)} 列）")
    r = rows.iloc[0]
    nn, dd = int(r["分子"]), int(r["分母"])
    filt = r["篩選條件"] if str(r["篩選條件"]) != "nan" else "見變項定義"
    text = (f"{item}：{nn}/{dd}（{nn / dd * 100:.1f}%）｜題目：{r['來源欄位／表']}"
            f"｜分母：{filt}｜信賴度 {r['信賴度']}")
    text = text.replace("%≥3", "評 3 分以上").replace("%≥4", "評 4 分以上")
    return {"n": nn, "d": dd, "field": field, "desc": text}


def F(fig, label, field="pct", by="n"):
    f = _FIGS["figures"][fig]
    for it in f["items"]:
        if it["label"] == label:
            nn = it.get(by)
            return {"n": nn, "d": it["d"], "field": field,
                    "desc": f"{label}：{nn}/{it['d']}（{nn / it['d'] * 100:.1f}%）｜圖表 {fig}"
                            f"｜{f.get('denomNote') or f.get('subtitle', '')}"}
    raise SystemExit(f"{fig} 沒有選項 {label}")


def X(name, where, n, d=None, pct=None, field="pct", note=""):
    df = _csv(name)
    for k, v in where.items():
        df = df[df[k] == v]
    if len(df) != 1:
        raise SystemExit(f"{name} 條件 {where} 找到 {len(df)} 列")
    r = df.iloc[0]
    nn = int(r[n]) if n else None
    dd = int(r[d]) if d else None
    val = float(r[pct]) if pct else (nn / dd if nn is not None and dd else None)
    if nn is not None and dd:
        shown = f"{nn}/{dd}（{val * 100:.1f}%）"
    elif pct:
        shown = f"{val * 100:.1f}%"
    else:
        shown = f"{nn if nn is not None else dd} 人"
    conf = f"｜信賴度 {r['信賴度']}" if "信賴度" in r and str(r["信賴度"]) != "nan" else ""
    return {"n": nn, "d": dd, "value": val, "field": field,
            "desc": f"{'／'.join(str(v) for v in where.values())}：{shown}｜來源 分析結果/{name}"
                    f"{('｜' + note) if note else ''}{conf}"}


