def RANK(fig, label, by="n", source="fig"):
    """名次＝比它多的選項數＋1（並列同名次）。"""
    if source == "fig":
        items = [(it["label"], it[by]) for it in _FIGS["figures"][fig]["items"]
                 if "其他" not in it["label"]]
    else:                                   # source = CSV 檔名，fig = (標籤欄, 數值欄)
        df = _csv(source)
        items = list(zip(df[fig[0]], df[fig[1]]))
    mine = dict(items)[label]
    rank = 1 + sum(1 for _, v in items if v > mine)
    ties = [k for k, v in items if v == mine and k != label]
    return {"rank": rank, "desc": f"「{label}」在 {len(items)} 個選項中排第 {rank}"
                                  + (f"（與「{'、'.join(ties)}」並列）" if ties else "")
                                  + f"｜依{'3 分以上人數' if by == 'n3plus' else '勾選人數'}排序"}


